import importlib.util
from pathlib import Path
import unittest
import hashlib
import json
import os
import subprocess
import sys
import wave
from array import array

SCRIPT = Path(__file__).parents[2] / 'data/scripts/local_ai/process_media.py'
DATA = Path(os.environ['LOCALCUT_WORKSPACE_ROOT'])
WORK = DATA / 'tests/localai'
class Contracts(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        WORK.mkdir(parents=True, exist_ok=True)

    def test_output_guard_and_same_input(self):
        spec = importlib.util.spec_from_file_location('local_media', SCRIPT)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        root = WORK
        occupied = root / 'occupied.txt'
        occupied.write_text('original', encoding='utf8')
        with self.assertRaises(ValueError):
            module.validate_output(occupied, occupied)
        with self.assertRaises(ValueError):
            module.validate_output(root / 'source.wav', occupied)
        self.assertEqual(occupied.read_text(encoding='utf8'), 'original')
    def test_operations_are_explicit(self):
        spec = importlib.util.spec_from_file_location('local_media', SCRIPT)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        self.assertEqual(set(module.OPERATIONS), {'denoise_audio','separate_vocals','remove_background','enhance_video','smooth_skin','cover_face','animate_face'})

class MediaContracts(unittest.TestCase):
    root = WORK
    runtime = DATA / 'local-ai'
    ffmpeg = SCRIPT.parents[3] / 'runtime/bin/ffmpeg.exe'
    ffprobe = ffmpeg.with_name('ffprobe.exe')

    @classmethod
    def setUpClass(cls):
        if not cls.ffmpeg.is_file() or not (cls.root / 'speech-mix.wav').is_file():
            raise unittest.SkipTest('Requires runtime FFmpeg and prepared media fixtures in workspace/tests/localai')

    def run_operation(self, operation, source, output, model=None, extra=()):
        command = [sys.executable, str(SCRIPT), '--operation', operation,
            '--input', str(source), '--output', str(output), '--ffmpeg', str(self.ffmpeg),
            '--ffprobe', str(self.ffprobe), '--model-root', str(model or self.runtime/'models'),
            '--runtime-root', str(self.runtime), *extra]
        process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
        try:
            stdout, stderr = process.communicate(timeout=12)
        except subprocess.TimeoutExpired:
            subprocess.run(['taskkill', '/PID', str(process.pid), '/T', '/F'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            process.communicate()
            raise
        result = subprocess.CompletedProcess(command, process.returncode, stdout, stderr)
        events = [json.loads(line) for line in result.stdout.splitlines()]
        return result, events[-1]

    def test_real_audio_preserves_source_and_duration(self):
        source = self.root/'speech-mix.wav'
        if not source.exists():
            self.skipTest('Speech fixture is generated by integration QA')
        output = self.root/'test-denoise.wav'
        output.unlink(missing_ok=True)
        before = hashlib.sha256(source.read_bytes()).hexdigest()
        result, final = self.run_operation('denoise_audio', source, output)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue(final['ok'])
        self.assertEqual(hashlib.sha256(source.read_bytes()).hexdigest(), before)
        def duration(path):
            raw = subprocess.check_output([str(self.ffprobe), '-v', 'error', '-show_entries',
                'format=duration', '-of', 'json', str(path)])
            return float(json.loads(raw)['format']['duration'])
        self.assertAlmostEqual(duration(source), duration(output), places=2)

    def test_nonempty_output_never_overwritten(self):
        source = self.root/'speech-mix.wav'
        output = self.root/'test-occupied.wav'
        output.write_bytes(b'keep this exact data')
        result, final = self.run_operation('denoise_audio', source, output)
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse(final['ok'])
        self.assertEqual(output.read_bytes(), b'keep this exact data')

    def test_missing_model_failure_cleans_reserved_output(self):
        source = self.root/'speech-mix.wav'
        output, background = self.root/'missing-vocals.wav', self.root/'missing-background.wav'
        output.write_bytes(b'')
        background.write_bytes(b'')
        result, final = self.run_operation('separate_vocals', source, output,
            self.root/'models-not-installed', ('--background-output', str(background)))
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse(final['ok'])
        self.assertFalse(output.exists())
        self.assertFalse(background.exists())

    def test_delayed_audio_is_rejected_without_clock_shift(self):
        source = DATA / 'tests/mediatasks/delayed-tone.mp4'
        if not source.is_file():
            self.skipTest('Delayed-audio fixture is not available')
        output = self.root/'test-delayed.wav'
        output.unlink(missing_ok=True)
        result, final = self.run_operation('denoise_audio', source, output)
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse(final['ok'])
        self.assertIn('offset', final['message'])
        self.assertFalse(output.exists())

    def test_short_audio_is_not_reported_as_full_source(self):
        source = DATA / 'tests/mediatasks/long-video-short-audio.mp4'
        if not source.is_file():
            self.skipTest('Short-audio fixture is not available')
        output = self.root/'test-short-audio.wav'
        output.unlink(missing_ok=True)
        result, final = self.run_operation('denoise_audio', source, output)
        self.assertNotEqual(result.returncode, 0)
        self.assertFalse(final['ok'])
        self.assertIn('duration', final['message'])
        self.assertFalse(output.exists())

    def test_denoise_does_not_shift_an_impulse(self):
        source, output = self.root/'impulse-source.wav', self.root/'impulse-denoised.wav'
        for rate in (44100, 48000):
            with self.subTest(sample_rate=rate):
                values = array('h', [0]*rate)
                values[rate//4] = 24000
                with wave.open(str(source), 'wb') as handle:
                    handle.setparams((1, 2, rate, 0, 'NONE', 'none'))
                    handle.writeframes(values.tobytes())
                output.unlink(missing_ok=True)
                result, final = self.run_operation('denoise_audio', source, output)
                self.assertEqual(result.returncode, 0, final)
                with wave.open(str(output), 'rb') as handle:
                    processed = array('h', handle.readframes(handle.getnframes()))
                self.assertEqual(len(processed), rate)
                self.assertLessEqual(abs(max(range(len(processed)), key=lambda i:abs(processed[i]))-rate//4), 1)

    def test_corrupted_mdat_fails_without_stderr_pipe_deadlock(self):
        source = self.root/'damaged-stream.mp4'
        subprocess.run([str(self.ffmpeg), '-v', 'error', '-y', '-f', 'lavfi', '-i',
            'testsrc2=s=128x128:r=25:d=20', '-c:v', 'libx264', '-g', '1', '-threads', '2', str(source)], check=True)
        damaged = bytearray(source.read_bytes())
        marker = damaged.index(b'mdat')
        size = int.from_bytes(damaged[marker-4:marker], 'big')
        damaged[marker+4:marker-4+size] = bytes(size-8)
        source.write_bytes(damaged)
        before = hashlib.sha256(damaged).hexdigest()
        for operation in ('enhance_video', 'remove_background', 'smooth_skin'):
            with self.subTest(operation=operation):
                output = self.root/('damaged-'+operation+'.mp4')
                output.unlink(missing_ok=True)
                result, final = self.run_operation(operation, source, output)
                self.assertNotEqual(result.returncode, 0)
                self.assertFalse(final['ok'])
                self.assertFalse(output.exists())
        self.assertEqual(hashlib.sha256(source.read_bytes()).hexdigest(), before)
if __name__ == '__main__': unittest.main()
